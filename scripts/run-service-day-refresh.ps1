# Weekly rebuild of Muhammad's service-day lookup, run from Windows Task Scheduler.
#
# Why this exists (2026-10-17): the cron daemon is stopped, and restarting it would also fire ~20
# other jobs, several of which write to live Jobber. The lookup silently froze on 2026-09-28 as a
# result and Muhammad was quoting days off it.
#
# Two halves, deliberately split:
#   1. The two builders run as plain node — no Claude involved. Both are read-only against Jobber
#      and OptimoRoute.
#   2. Republishing the hosted page needs the Artifact tool, so a headless Claude runs with an
#      allowlist of exactly that tool plus Read. It cannot run shell commands or edit files.
#
# Install / remove the weekly task (Monday 06:30, after the week is set in Jobber):
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\run-service-day-refresh.ps1 -Install
#   schtasks /Delete /TN "GotMoles Service Day Lookup" /F
# Run now:
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\run-service-day-refresh.ps1
param([switch]$Install)

$Root = Split-Path -Parent $PSScriptRoot
$Lookup = Join-Path $Root 'projects\briefs\callrail-faq\service-day-lookup'
$LogDir = Join-Path $Root 'cron\logs'

if ($Install) {
  $self = Join-Path $PSScriptRoot 'run-service-day-refresh.ps1'
  schtasks /Create /TN "GotMoles Service Day Lookup" /SC WEEKLY /D MON /ST 06:30 /F `
    /TR "powershell -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$self`""
  exit $LASTEXITCODE
}

New-Item -ItemType Directory -Force -Path $LogDir | Out-Null
$log = Join-Path $LogDir ("service-day-refresh-{0}.log" -f (Get-Date -Format 'yyyy-MM-dd_HHmm'))
Set-Location $Root
$start = Get-Date

& node projects/briefs/callrail-faq/service-day-lookup/build-zip-day-lookup.mjs *>> $log
if ($LASTEXITCODE -ne 0) { "STEP 1 FAILED (zip builder) - nothing republished" >> $log; exit 1 }

& node projects/briefs/technician-route-automation/build-address-day-lookup.mjs `
  --grid=../callrail-faq/service-day-lookup/service-day-grid.json *>> $log
if ($LASTEXITCODE -ne 0) { "STEP 2 FAILED (address builder) - nothing republished" >> $log; exit 1 }

# A fast "success" without a fresh file is the 2026-08-04 failure: never publish a stale page.
$addr = Join-Path $Lookup 'address-day-lookup.artifact.html'
if ((Get-Item $addr).LastWriteTime -lt $start) { "Address page not rewritten - nothing republished" >> $log; exit 1 }

$prompt = @"
Republish two existing artifacts with the Artifact tool. Do nothing else.
1. file_path = $Lookup\address-day-lookup.artifact.html
   url = https://claude.ai/code/artifact/20e073bc-db4d-4f9c-b49e-9adc55725fba
2. file_path = $Lookup\zip-day-lookup.artifact.html
   url = https://claude.ai/code/artifact/591eb026-6906-4549-a326-f5d08fbcddf1
Always pass the url so the existing links keep working.
Each page is fully generated by a builder, so the new file supersedes the live version entirely.
If a publish is refused because you have not viewed the live version, Read the first 60 lines of
the saved copy it names (to confirm it is the same generated page), then publish the same file again.
Report success or the exact error for each.
"@
Remove-Item Env:CLAUDECODE -ErrorAction SilentlyContinue
& claude -p --model sonnet --output-format text --permission-mode dontAsk `
  --allowedTools "Artifact" "Read" -- $prompt *>> $log
